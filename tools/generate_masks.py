def rasterize(svg_str, filename):
    html_content = f'''<!DOCTYPE html>
<html>
<head>
<style>
* {{ margin: 0; padding: 0; box-sizing: border-box; }}
html, body {{ background: black; width: 120px; height: 120px; overflow: hidden; }}
svg {{ width: 120px; height: 120px; display: block; }}
</style>
</head>
<body>
{svg_str}
</body>
</html>'''
    html_file = os.path.abspath(f"tools/{filename}.html")
    with open(html_file, "w", encoding="utf-8") as f:
        f.write(html_content)
    
    options = Options()
    options.add_argument('--headless')
    options.add_argument('--window-size=800,800')
    options.add_argument('--force-device-scale-factor=1')
    driver = webdriver.Edge(options=options)
    driver.get(f"file:///{html_file.replace(os.sep, '/')}")
    el = driver.find_element('tag name', 'svg')
    png_bytes = el.screenshot_as_png
    driver.quit()
    
    img = Image.open(io.BytesIO(png_bytes)).convert('L')
    res = img.resize((16, 16), Image.Resampling.LANCZOS)
    res.save(f"tools/{filename}.png")
    
    data = [int(res.getpixel((x, y))) for y in range(16) for x in range(16)]
    return data, res

