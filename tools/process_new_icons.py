os.makedirs("scratch/rendered_icons", exist_ok=True)

chrome_path = r"C:\Program Files\Google\Chrome\Application\chrome.exe"

masks_16x16 = {}

for name, svg_content in SVG_ICONS.items():
    svg_file = f"icons/{name}.svg"
    with open(svg_file, "w", encoding="utf-8") as f:
        f.write(svg_content)
    print(f"Saved {svg_file}")

    # Build HTML wrapper with black background and white icon for high-contrast alpha capture
    html_content = f"""<!DOCTYPE html>
<html>
<head><style>
* {{ margin: 0; padding: 0; }}
body {{ background-color: #000000; display: flex; align-items: center; justify-content: center; width: 64px; height: 64px; }}
svg {{ width: 56px; height: 56px; }}
</style></head>
<body>
{svg_content.replace('fill="#868686"', 'fill="#FFFFFF"')}
</body>
</html>"""
    html_file = f"scratch/rendered_icons/{name}.html"
    png_file = f"scratch/rendered_icons/{name}.png"
    with open(html_file, "w", encoding="utf-8") as f:
        f.write(html_content)

    cmd = [
        chrome_path,
        "--headless",
        "--disable-gpu",
        "--window-size=64,64",
        f"--screenshot={os.path.abspath(png_file)}",
        os.path.abspath(html_file)
    ]
    subprocess.run(cmd, check=True, capture_output=True)
    
    # Load 64x64 PNG and downsample to 16x16 with Lanczos for subpixel antialiasing
    im = Image.open(png_file).convert("L")
    im_16 = im.resize((16, 16), Image.Resampling.LANCZOS)
    im_16.save(f"scratch/rendered_icons/{name}_16.png")

    # Generate 256-byte array
    arr = list(im_16.getdata())
    masks_16x16[name] = arr
    print(f"Rasterized {name}: {len(arr)} bytes, max brightness {max(arr)}")

with open("scratch/new_masks.h", "w", encoding="utf-8") as f:
    for name, arr in masks_16x16.items():
        f.write(f"static const uint8_t {name}Mask[256] = {{\n")
        f.write(",".join(str(x) for x in arr))
        f.write("\n};\n\n")

print("Generated scratch/new_masks.h successfully!")
